// Generates migrations/0003_current_menu.sql from src/lib/content/seed.ts.
// Run from app/: `bun scripts/gen-seed.ts`. It retires the old crab-centric
// courses and articles, then adds the current menu and journal with
// INSERT OR IGNORE, so rows the owner has edited in /admin are never overwritten.
// (0002_seed.sql is the original seed and is left as it was applied.)
import { writeFileSync } from "node:fs";
import { RETIRED_CATEGORY_SLUGS, RETIRED_POST_IDS, SEED_CATEGORIES, SEED_DISHES, SEED_POSTS } from "../src/lib/content/seed";

const q = (value: string | number | boolean | null) => {
  if (value === null) return "NULL";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "1" : "0";
  return `'${value.replace(/'/g, "''")}'`;
};
const row = (values: (string | number | boolean | null)[]) => values.map(q).join(", ");

const lines: string[] = [
  "-- Generated by scripts/gen-seed.ts from src/lib/content/seed.ts. Do not edit by hand.",
  "-- Retires the crab-centric seed, then adds the current menu. INSERT OR IGNORE never",
  "-- overwrites content edited in /admin.",
  "",
  `DELETE FROM menu_categories WHERE slug IN (${row(RETIRED_CATEGORY_SLUGS)});`,
  `DELETE FROM journal_posts WHERE id IN (${row(RETIRED_POST_IDS)});`,
  "",
];

for (const c of SEED_CATEGORIES) {
  lines.push(
    `INSERT OR IGNORE INTO menu_categories (slug, title, subtitle, story, mood, image, image_alt, icon, sort) VALUES (${row([
      c.slug, c.title, c.subtitle, c.story, c.mood, c.image, c.imageAlt, c.icon, c.sort,
    ])});`,
  );
}
lines.push("");
for (const d of SEED_DISHES) {
  lines.push(
    `INSERT OR IGNORE INTO dishes (id, slug, name, description, price, category, image, image_alt, dietary, featured, published, sort) VALUES (${row([
      d.id, d.slug, d.name, d.description, d.price, d.category, d.image, d.imageAlt, JSON.stringify(d.dietary), d.featured, d.published, d.sort,
    ])});`,
  );
}
lines.push("");
for (const p of SEED_POSTS) {
  lines.push(
    `INSERT OR IGNORE INTO journal_posts (id, slug, title, category, excerpt, cover, cover_alt, body, author, published_at, published) VALUES (${row([
      p.id, p.slug, p.title, p.category, p.excerpt, p.cover, p.coverAlt, p.body, p.author, p.publishedAt, p.published,
    ])});`,
  );
}

writeFileSync(new URL("../migrations/0003_current_menu.sql", import.meta.url), `${lines.join("\n")}\n`);
console.log(`wrote ${SEED_CATEGORIES.length} categories, ${SEED_DISHES.length} dishes, ${SEED_POSTS.length} posts`);
